/** Markdown "worked solution" of every value, in the order it was found. */
import { fmtQ } from '../physics/units';
import { VAR } from '../solver/variables';
import type { SolveResult } from '../solver/types';

const STATUS_TEXT: Record<string, string> = {
  input: 'entered',
  calculated: 'calculated',
  assumed: 'assumed',
  optimised: 'optimised',
  section: 'from the section',
  material: 'from the material',
  constant: 'fixed by the planform',
  conflict: 'in conflict',
};

export function buildReport(
  res: SolveResult,
  title: string,
  units: Record<string, string | undefined>,
): string {
  const lines = [
    `# ${title}`,
    '',
    `Generated by Hydrofoil Designer on ${new Date().toISOString().slice(0, 10)}.`,
    '',
  ];
  if (res.optimisation) lines.push(`**Fit:** ${res.optimisation.message}`, '');
  if (res.warnings.length) {
    lines.push('## Warnings', '');
    for (const w of res.warnings) lines.push(`- ${w}`);
    lines.push('');
  }
  const derivs = Object.values(res.derivations).sort((a, b) => a.order - b.order);
  const groups: [string, (s: string) => boolean][] = [
    ['Your inputs', (s) => s === 'input' || s === 'conflict'],
    ['Assumptions and optimised choices', (s) => s === 'assumed' || s === 'optimised'],
    [
      'Section, material and planform data',
      (s) => s === 'section' || s === 'material' || s === 'constant',
    ],
    ['Calculations', (s) => s === 'calculated'],
  ];
  for (const [heading, pick] of groups) {
    const ds = derivs.filter((d) => pick(d.status));
    if (!ds.length) continue;
    lines.push(`## ${heading}`, '');
    for (const d of ds) {
      const def = VAR[d.varId];
      if (!def) continue;
      const val = fmtQ(d.value, def.quantity, units[d.varId]);
      lines.push(`### ${def.label} — ${val} (${STATUS_TEXT[d.status] ?? d.status})`, '');
      if (d.formula) lines.push('$$', d.formula, '$$', '');
      if (d.substitution && d.status === 'calculated') lines.push('$$', d.substitution, '$$', '');
      if (d.method && d.status !== 'input') lines.push(`*${d.method}*`, '');
      if (d.note) lines.push(d.note, '');
    }
  }
  return lines.join('\n');
}
